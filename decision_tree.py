import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn.tree import DecisionTreeClassifier, plot_tree
from sklearn.metrics import accuracy_score, classification_report
import matplotlib.pyplot as plt

# 1. Load the dataset
df = pd.read_excel("/content/india_weather_rainfall_data.xlsx")

# 2. Display dataset information
print(df.head())
print(df.columns)

# 3. Remove missing values
df = df.dropna()

# 4. Select input features
# Change these column names according to your dataset
X = df[["avg_temp", "wind_speed", "air_pressure"]]

# 5. Select target column
y = df["rainfall"]

# 6. Convert target into Rain/No Rain
# If Rainfall is numerical:
y = (y > 0).astype(int)

# 7. Split data into training and testing
X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.30, random_state=42
)

# 8. Create Decision Tree model
model = DecisionTreeClassifier(
    criterion="entropy",
    max_depth=5,
    random_state=42
)

# 9. Train the model
model.fit(X_train, y_train)

# 10. Make predictions
y_pred = model.predict(X_test)

# 11. Check accuracy
accuracy = accuracy_score(y_test, y_pred)
print("Accuracy:", accuracy)

# 12. Classification report
print("\nClassification Report:")
print(classification_report(y_test, y_pred))

# 13. Display Decision Tree
plt.figure(figsize=(15, 8))
plot_tree(
    model,
    feature_names=X.columns,
    class_names=["No Rain", "Rain"],
    filled=True
)
plt.show()

# 14. Test with new weather data
# Note: The 'new_data' array needs to match the number of features used for training.
# Since Humidity was removed, this array should now have 3 values corresponding to avg_temp, wind_speed, and air_pressure.
new_data_values = [[30, 12, 1005]] # Example values for avg_temp, wind_speed, air_pressure
new_data = pd.DataFrame(new_data_values, columns=X.columns) # Convert to DataFrame with feature names

prediction = model.predict(new_data)

if prediction[0] == 1:
    print("Prediction: Rain")
else:
    print("Prediction: No Rain")

